import type { SketchStroke } from "../components/SketchGroup";
import { hatch } from "../sketch";

const s = (
  d: string,
  start: number,
  dur = 12,
  extra: Partial<SketchStroke> = {},
): SketchStroke => ({ d, start, dur, ...extra });

const hatchStrokes = (
  x: number,
  y: number,
  w: number,
  h: number,
  count: number,
  start: number,
  gap = 1.4,
): SketchStroke[] =>
  hatch(x, y, w, h, count).map((d, i) =>
    s(d, start + i * gap, 7, { width: 2.2, tone: "hatch" }),
  );

